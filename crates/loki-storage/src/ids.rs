//! Opaque, branded identifier newtypes mirroring
//! `packages/contracts/src/ids.ts` / `brand.ts`'s `idSchema` factory — per
//! `Docs/graph/tasks/DAT-001.md` §3: "until a Rust contracts crate/codegen
//! exists, use the Rust newtype/struct shape that mirrors the TS contract's
//! cited `Docs/SPEC.md` section, and cite the same section in a doc
//! comment, not the TS file." Each type below cites the exact
//! `Docs/SPEC.md` entity section its ID belongs to; the shared *shape* rule
//! (non-empty, <= 200 chars, charset `[A-Za-z0-9._:-]`) is `Docs/SPEC.md`
//! Section 1's "every externally visible identifier is opaque and stable,"
//! bounded the same conservative way `packages/contracts/src/brand.ts`
//! documents (a shared wire *shape*, not one specific ID-generation
//! scheme).
//!
//! This crate does not depend on `@lokiai/contracts` (a TypeScript
//! package, not consumable from Rust yet) — these newtypes are an
//! independent Rust transcription of the same normative `Docs/` source,
//! kept honest by citing `Docs/` directly rather than treating the TS file
//! as the source of truth.
//!
//! IDs are validated on construction ([`DeviceId::new`] etc.), not
//! generated by this crate: ID minting is a domain-layer decision owned by
//! whichever subsystem first assigns one (`packages/contracts/src/brand.ts`
//! deliberately does not pin one generation scheme either) — this crate
//! only ever receives and validates already-minted IDs.

use crate::error::StorageError;

/// Maximum accepted length for any opaque LokiAI identifier — mirrors
/// `packages/contracts/src/brand.ts` `ID_MAX_LENGTH`.
const ID_MAX_LENGTH: usize = 200;

fn validate_id(kind: &'static str, value: &str) -> Result<(), StorageError> {
    if value.is_empty() {
        return Err(StorageError::InvalidId {
            kind,
            reason: "must not be empty".to_string(),
        });
    }
    if value.chars().count() > ID_MAX_LENGTH {
        return Err(StorageError::InvalidId {
            kind,
            reason: format!("exceeds maximum length of {ID_MAX_LENGTH}"),
        });
    }
    if !value
        .chars()
        .all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | ':' | '-'))
    {
        return Err(StorageError::InvalidId {
            kind,
            reason: "contains unsupported characters (allowed: A-Z a-z 0-9 . _ : -)".to_string(),
        });
    }
    Ok(())
}

macro_rules! define_id {
    ($(#[$meta:meta])* $name:ident) => {
        $(#[$meta])*
        #[derive(Debug, Clone, PartialEq, Eq, Hash)]
        pub struct $name(String);

        impl $name {
            /// Validates and wraps `value`. Mirrors
            /// `packages/contracts/src/brand.ts` `idSchema(...).parse(...)`.
            pub fn new(value: impl Into<String>) -> Result<Self, StorageError> {
                let value = value.into();
                validate_id(stringify!($name), &value)?;
                Ok(Self(value))
            }

            /// Borrows the underlying opaque string.
            pub fn as_str(&self) -> &str {
                &self.0
            }

            /// Consumes `self`, returning the underlying opaque string.
            pub fn into_string(self) -> String {
                self.0
            }
        }

        impl std::fmt::Display for $name {
            fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                f.write_str(&self.0)
            }
        }

        impl std::convert::TryFrom<String> for $name {
            type Error = StorageError;
            fn try_from(value: String) -> Result<Self, Self::Error> {
                Self::new(value)
            }
        }

        impl std::convert::TryFrom<&str> for $name {
            type Error = StorageError;
            fn try_from(value: &str) -> Result<Self, Self::Error> {
                Self::new(value)
            }
        }
    };
}

