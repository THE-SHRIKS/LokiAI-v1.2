#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn accepts_valid_id() {
        assert!(DeviceId::new("dev_abc-123.x:1").is_ok());
    }

    #[test]
    fn rejects_empty() {
        assert!(matches!(
            DeviceId::new(""),
            Err(StorageError::InvalidId { .. })
        ));
    }

    #[test]
    fn rejects_oversized() {
        let too_long = "a".repeat(ID_MAX_LENGTH + 1);
        assert!(matches!(
            DeviceId::new(too_long),
            Err(StorageError::InvalidId { .. })
        ));
    }

    #[test]
    fn accepts_exactly_max_length() {
        let exactly_max = "a".repeat(ID_MAX_LENGTH);
        assert!(DeviceId::new(exactly_max).is_ok());
    }

    #[test]
    fn rejects_bad_charset() {
        assert!(matches!(
            DeviceId::new("dev id with spaces"),
            Err(StorageError::InvalidId { .. })
        ));
        assert!(matches!(
            DeviceId::new("dev/id"),
            Err(StorageError::InvalidId { .. })
        ));
        assert!(matches!(
            DeviceId::new("dev@id"),
            Err(StorageError::InvalidId { .. })
        ));
    }

    #[test]
    fn error_names_the_concrete_type() {
        match DeviceId::new("") {
            Err(StorageError::InvalidId { kind, .. }) => assert_eq!(kind, "DeviceId"),
            other => panic!("expected InvalidId, got {other:?}"),
        }
        match JobId::new("") {
            Err(StorageError::InvalidId { kind, .. }) => assert_eq!(kind, "JobId"),
            other => panic!("expected InvalidId, got {other:?}"),
        }
    }

    #[test]
    fn try_from_str_and_string_both_work() {
        use std::convert::TryFrom;
        assert!(DeviceId::try_from("dev-1").is_ok());
        assert!(DeviceId::try_from(String::from("dev-1")).is_ok());
    }

    #[test]
    fn display_matches_as_str() {
        let id = DeviceId::new("dev-1").unwrap();
        assert_eq!(id.to_string(), id.as_str());
    }
}
